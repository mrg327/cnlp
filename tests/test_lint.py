from __future__ import annotations

import shutil
from pathlib import Path

from cnlp import lint

ROOT = Path(__file__).resolve().parent.parent


def mk(tmp_path: Path, files: dict[str, str]) -> Path:
    for rel, text in files.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return tmp_path


def rules(fs):
    return [f.rule for f in fs]


def test_pin_field_designator(tmp_path):
    src = "#include <stdio.h>\nvoid f(void){\n  x_t c = {\n    .flags.enable_internal_pullup = true,\n  };\n}\n"
    fs = lint.run(mk(tmp_path, {"main/main.c": src}))
    assert rules(fs) == ["LINT_DRIVER_PIN_FIELD"]
    assert fs[0].message.startswith("main/main.c:4: ")
    assert "board_<bus>_config()" in fs[0].message


def test_pin_field_assignment(tmp_path):
    fs = lint.run(
        mk(tmp_path, {"main/a.c": "void f(void){ cfg.sda_io_num = 21; cfg.pull_up_en = 1; }\n"})
    )
    assert rules(fs) == ["LINT_DRIVER_PIN_FIELD"] * 2


def test_direct_gpio(tmp_path):
    src = "void f(void){\n\n  gpio_config(&c);\n}\n"
    fs = lint.run(mk(tmp_path, {"main/main.c": src}))
    assert rules(fs) == ["LINT_DIRECT_GPIO"]
    assert fs[0].message.startswith("main/main.c:3: ")
    assert "board_pins_init()" in fs[0].message


def test_comments_and_strings_ignored(tmp_path):
    src = '// gpio_config(&c);\n/* gpio_set_direction(1,2) */\nconst char *s = "gpio_config(";\n'
    assert lint.run(mk(tmp_path, {"main/main.c": src})) == []


def test_pure_core(tmp_path):
    fs = lint.run(
        mk(tmp_path, {"core/logic.c": '#include "freertos/FreeRTOS.h"\n#include "esp_log.h"\n'})
    )
    assert rules(fs) == ["LINT_PURE_CORE"] * 2


def test_pure_core_clean(tmp_path):
    assert lint.run(mk(tmp_path, {"core/logic.c": "#include <stdint.h>\n"})) == []


def test_banned_adc(tmp_path):
    fs = lint.run(mk(tmp_path, {"main/main.c": "#include <driver/adc.h>\n#include <Arduino.h>\n"}))
    assert rules(fs) == ["LINT_BANNED_API"] * 2
    assert "adc_oneshot" in fs[0].message


def test_unlisted_include(tmp_path):
    fs = lint.run(
        mk(
            tmp_path,
            {
                "main/main.c": '#include <soc/gpio_reg.h>\n#include "mine.h"\n#include "nope.h"\n',
                "main/mine.h": "",
            },
        )
    )
    assert rules(fs) == ["LINT_INCLUDE"] * 2
    assert "nope.h" in fs[1].message


def test_generated_skipped(tmp_path):
    src = "/* GENERATED by cnlp */\n#include <soc/gpio_reg.h>\nvoid f(void){gpio_config(0);}\n"
    assert lint.run(mk(tmp_path, {"components/board/b.c": src})) == []


def test_profile_override(tmp_path):
    files = {"main/main.c": "#include <soc/gpio_reg.h>\n#include <driver/i2c.h>\n"}
    assert len(lint.run(mk(tmp_path, files))) == 2
    (tmp_path / "cnlp-profile.yaml").write_text(
        "include_allow: ['soc/gpio_reg.h']\ninclude_ban: {driver/i2c.h: ''}\n"
    )
    assert lint.run(tmp_path) == []


def test_profile_add_ban(tmp_path):
    p = mk(
        tmp_path,
        {
            "main/main.c": "#include <stdio.h>\n",
            "cnlp-profile.yaml": "include_ban: {stdio.h: use esp_log}\n",
        },
    )
    fs = lint.run(p)
    assert rules(fs) == ["LINT_BANNED_API"] and "esp_log" in fs[0].message


def test_parse_warning(tmp_path):
    fs = lint.run(mk(tmp_path, {"main/main.c": "void f(void){ int = ;;; }}}\n"}))
    assert "LINT_PARSE" in rules(fs)


def test_skip_build_dirs(tmp_path):
    assert lint.run(mk(tmp_path, {"main/build/x.c": "void f(void){gpio_config(0);}\n"})) == []


def test_sorted(tmp_path):
    p = mk(
        tmp_path,
        {
            "main/b.c": "void f(void){gpio_config(0);}\n",
            "main/a.c": "\n\nvoid f(void){gpio_config(0);gpio_reset_pin(1);}\n",
        },
    )
    assert [f.message.split(":")[0] for f in lint.run(p)] == ["main/a.c", "main/a.c", "main/b.c"]


def test_blinky_clean(tmp_path):
    dst = tmp_path / "blinky"
    shutil.copytree(ROOT / "examples/blinky", dst, ignore=shutil.ignore_patterns("build"))
    assert lint.run(dst) == []
    shutil.rmtree(dst / "components")
    assert lint.run(dst) == []
