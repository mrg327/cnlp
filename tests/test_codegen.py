import dataclasses
from pathlib import Path

import pytest

from cnlp import codegen, manifest

FIXTURE = Path(__file__).parent / "fixtures" / "manifests" / "blinky.yaml"


@pytest.fixture
def m():
    return manifest.load(FIXTURE)


@pytest.fixture
def out(m, tmp_path):
    codegen.generate(m, tmp_path)
    return tmp_path


def test_deterministic(m, tmp_path):
    a = codegen.generate(m, tmp_path / "a")
    b = codegen.generate(m, tmp_path / "b")
    assert a == b
    assert [f["path"] for f in a] == sorted(f["path"] for f in a)
    assert {f["path"] for f in a} == {
        "CMakeLists.txt", "board_pins.c", "board_drivers.c",
        "include/board_pins.h", "include/board_drivers.h"}


def test_banner_everywhere(m, out):
    import hashlib
    sha = hashlib.sha256(m.to_yaml().encode()).hexdigest()
    for f in out.rglob("*"):
        if f.is_file():
            t = f.read_text()
            assert "GENERATED by cnlp from the manifest" in t
            assert f"cnlp-manifest-sha256: {sha}" in t


def test_header(out):
    h = (out / "include/board_pins.h").read_text()
    assert "#define PIN_LED GPIO_NUM_25" in h
    assert "#define PIN_BUTTON GPIO_NUM_4" in h
    assert "#define PIN_I2C0_SDA GPIO_NUM_21" in h
    assert "GPIO_IS_VALID_OUTPUT_GPIO(PIN_LED)" in h
    assert "GPIO_IS_VALID_GPIO(PIN_BUTTON)" in h
    assert "GPIO_IS_VALID_OUTPUT_GPIO(PIN_BUTTON)" not in h
    assert "chip-wide" in h
    assert "(1ULL<<4)|(1ULL<<21)|(1ULL<<22)|(1ULL<<25)" in h
    assert (1 << 4 | 1 << 21 | 1 << 22 | 1 << 25) == 0x2600010
    assert "void board_pins_init(void);" in h and "void board_pins_readback(void);" in h


def test_gpio_config_fields(out):
    c = (out / "board_pins.c").read_text()
    assert c.count("gpio_config_t") == 2  # i2c pins left to the driver
    for field in (".pin_bit_mask", ".mode", ".pull_up_en", ".pull_down_en", ".intr_type"):
        assert c.count(field) == 2
    assert "GPIO_PULLUP_ENABLE" in c and "GPIO_INTR_DISABLE" in c
    assert "PIN_I2C0" not in c
    assert "=== CNLP READBACK BEGIN ===" in c and "=== CNLP READBACK END ===" in c
    assert "gpio_dump_io_configuration(stdout, BOARD_PINS_MASK)" in c


def test_interrupt_pin(m, tmp_path):
    pins = tuple(dataclasses.replace(p, function="interrupt") if p.role == "button" else p
                 for p in m.pins)
    codegen.generate(dataclasses.replace(m, pins=pins), tmp_path)
    assert "GPIO_INTR_ANYEDGE" in (tmp_path / "board_pins.c").read_text()


def test_i2c(out):
    d = (out / "board_drivers.c").read_text()
    assert "board_i2c0_config" in d
    assert ".sda_io_num = PIN_I2C0_SDA" in d and ".scl_io_num = PIN_I2C0_SCL" in d
    assert ".glitch_ignore_cnt = 7" in d
    assert ".flags.enable_internal_pullup = false" in d
    assert "esp_driver_i2c" in (out / "CMakeLists.txt").read_text()


def test_no_buses(m, tmp_path):
    pins = tuple(p for p in m.pins if p.function != "i2c")
    codegen.generate(dataclasses.replace(m, pins=pins), tmp_path)
    assert (tmp_path / "board_drivers.c").exists()
    assert "esp_driver_i2c" not in (tmp_path / "CMakeLists.txt").read_text()


def test_lone_sda(m, tmp_path):
    pins = tuple(p for p in m.pins if p.bus != "i2c0_scl")
    with pytest.raises(codegen.CodegenError):
        codegen.generate(dataclasses.replace(m, pins=pins), tmp_path)
