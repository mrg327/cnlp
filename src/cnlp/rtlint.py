def _txt(n: Node) -> str:
    return (n.text or b"").decode("utf-8", "replace")


def _walk(node: Node):
    stack = [node]
    while stack:
        n = stack.pop()
        yield n
        stack.extend(reversed(n.children))


def _line(n: Node) -> int:
    return n.start_point[0] + 1


@dataclass
class Call:
    name: str
    node: Node
    rel: str

    @property
    def line(self) -> int:
        return _line(self.node)

    def args(self) -> list[Node]:
        a = self.node.child_by_field_name("arguments")
        return [c for c in (a.named_children if a else []) if c.type != "comment"]


@dataclass
class Func:
    name: str
    node: Node
    rel: str
    calls: list[Call] = field(default_factory=list)


@dataclass
class Unit:
    rel: str
    root: Node
    funcs: list[Func]


def _func_name(fd: Node) -> str | None:
    d = fd.child_by_field_name("declarator")
    while d is not None and d.type != "function_declarator":
        d = d.child_by_field_name("declarator")
    if d is None:
        return None
    nm = d.child_by_field_name("declarator")
    return _txt(nm) if nm is not None and nm.type == "identifier" else None


def _calls_in(node: Node, rel: str) -> list[Call]:
    out = []
    for n in _walk(node):
        if n.type == "call_expression":
            fn = n.child_by_field_name("function")
            if fn is not None and fn.type == "identifier":
                out.append(Call(_txt(fn), n, rel))
    return out


class Project:
    def __init__(self, project: Path, files: list[Path]):
        self.units: list[Unit] = []
        self.funcs: dict[str, list[Func]] = {}
        self.macros: dict[str, str] = {}
        for p in files:
            data = p.read_bytes()
            if any(MARKER.encode() in ln for ln in data.splitlines()[:5]):
                continue
            root = _PARSER.parse(data).root_node
            rel = p.relative_to(project).as_posix()
            funcs = []
            for n in _walk(root):
                if n.type == "function_definition":
                    name = _func_name(n)
                    body = n.child_by_field_name("body")
                    if name and body is not None:
                        f = Func(name, n, rel, _calls_in(body, rel))
                        funcs.append(f)
                        self.funcs.setdefault(name, []).append(f)
                elif n.type == "preproc_def":
                    nm, val = n.child_by_field_name("name"), n.child_by_field_name("value")
                    if nm is not None and val is not None:
                        self.macros[_txt(nm)] = _STRIP_RE.sub(" ", _txt(val)).strip()
                elif n.type == "declaration":
                    self._const_init(n)
            self.units.append(Unit(rel, root, funcs))

    def _const_init(self, decl: Node) -> None:
        if not any(c.type == "type_qualifier" and _txt(c) == "const" for c in decl.children):
            return
        for c in decl.children:
            if c.type == "init_declarator":
                d, v = c.child_by_field_name("declarator"), c.child_by_field_name("value")
                if d is not None and d.type == "identifier" and v is not None:
                    self.macros[_txt(d)] = _txt(v)

    def callees(self, name: str) -> list[str]:
        seen, out = set(), []
        for f in self.funcs.get(name, []):
            for c in f.calls:
                if c.name in self.funcs and c.name not in seen:
                    seen.add(c.name)
                    out.append(c.name)
        return out

    def reach(self, entry: str) -> dict[str, str | None]:
        """BFS over direct calls: function -> parent in the shortest chain."""
        parent: dict[str, str | None] = {entry: None}
        q = deque([entry])
        while q:
            cur = q.popleft()
            for c in self.callees(cur):
                if c not in parent:
                    parent[c] = cur
                    q.append(c)
        return parent

    def is_zero(self, node: Node | str, depth: int = 0) -> bool:
        s = re.sub(r"\s+", "", node if isinstance(node, str) else _txt(node))
        for _ in range(8):
            m = re.fullmatch(r"pdMS_TO_TICKS\((.*)\)", s)
            if m:
                s = m.group(1)
                continue
            s = re.sub(r"^\(\w+(?:\*)?\)(?=[\w(])", "", s)
            if s.startswith("(") and s.endswith(")") and s.count("(") == s.count(")"):
                s = s[1:-1]
                continue
            break
        if _ZERO_RE.match(s):
            return True
        if re.fullmatch(r"[A-Za-z_]\w*", s) and s in self.macros and depth < 6:
            return self.is_zero(self.macros[s], depth + 1)
        return False


def _chain(parent: dict[str, str | None], name: str) -> list[str]:
    out = [name]
    while parent[out[-1]] is not None:
        out.append(parent[out[-1]])  # type: ignore[arg-type]
    return out[::-1]


class Checker:
    def __init__(self, project: Path, files: list[Path], cfg: dict[str, Any]):
        self.P = Project(project, files)
        self.cfg = cfg or {}
        self.allowed = set(self.cfg.get("allowed_blocking_in_realtime") or [])
        self.extra_block = set(self.cfg.get("blocking_calls") or [])
        self.out: list[Finding] = []
        self._seen: set[tuple[str, str, int, str]] = set()
        self.tasks = self._tasks()

    def add(self, rule: str, sev: str, rel: str, line: int, msg: str, key: str = "") -> None:
        k = (rule, rel, line, key or msg)
        if k in self._seen:
            return
        self._seen.add(k)
        self.out.append(Finding(rule, sev, f"{rel}:{line}: {msg}"))  # type: ignore[arg-type]

    def _tasks(self) -> dict[str, bool]:
        """entry function -> realtime?"""
        tasks: dict[str, bool] = {}
        for spec in (self.cfg.get("tasks") or {}).values():
            if isinstance(spec, dict) and spec.get("entry"):
                tasks[spec["entry"]] = bool(spec.get("realtime"))
        for fl in self.P.funcs.values():
            for f in fl:
                for c in f.calls:
                    if c.name.startswith("xTaskCreate") and c.args():
                        a = c.args()[0]
                        if a.type == "identifier":
                            tasks.setdefault(_txt(a), False)
        return tasks

    # ---- RT1 -------------------------------------------------------------
    def classify_block(self, c: Call) -> str | None:
        n = c.name
        if n in self.allowed:
            return None
        if n in LOG_CALLS or n.startswith(("ESP_LOG", "ESP_EARLY_LOG")):
            return "logging/printing"
        if n in MEM_CALLS or n.startswith("heap_caps_"):
            return "heap allocation"
        if n in SYNC_CALLS or (n.startswith("xSemaphoreCreate")):
            return "mutex/semaphore"
        if n in DELAY_CALLS:
            return "a delay"
        if n in TIMED:
            args = c.args()
            i = TIMED[n]
            if len(args) <= i or not self.P.is_zero(args[i]):
                return "a call with a non-zero timeout"
        return None

    def rt1(self) -> None:
        for entry, rt in self.tasks.items():
            if not rt or entry not in self.P.funcs:
                continue
            parent = self.P.reach(entry)
            for fn in parent:
                for f in self.P.funcs[fn]:
                    for c in f.calls:
                        kind = self.classify_block(c)
                        if kind:
                            chain = " → ".join([*_chain(parent, fn), c.name])
                            self.add(
                                "RT1_AUDIO_BLOCKING",
                                "error",
                                f.rel,
                                c.line,
                                f"{c.name}() is {kind} in the real-time path ({chain}). "
                                f"Anywhere in {entry}'s loop or the functions it calls counts, "
                                "before or after the allowed blocking call; moving it within "
                                "the task does not fix it. Remove it, or hand the data to a "
                                "lower-priority task (e.g. a volatile counter or a zero-timeout "
                                "queue) and log there (real-time rule 1)",
                                key=c.name,
                            )

    # ---- RT2 -------------------------------------------------------------
    def rt2(self) -> None:
        for fl in self.P.funcs.values():
            for f in fl:
                for c in f.calls:
                    i = QUEUE_TIMEOUT.get(c.name)
                    if i is None:
                        continue
                    args = c.args()
                    if len(args) <= i:
                        continue
                    if not self.P.is_zero(args[i]):
                        self.add(
                            "RT2_QUEUE_TIMEOUT",
                            "error",
                            f.rel,
                            c.line,
                            f"{c.name}() timeout is '{_txt(args[i])}', not 0; note queues use "
                            "zero-timeout send and receive (real-time rule 2)",
                        )

    # ---- RT3 -------------------------------------------------------------
    def _globals(self) -> set[str]:
        names: set[str] = set()

        def decl_names(d: Node | None) -> list[str]:
            out = []
            while d is not None:
                if d.type == "identifier":
                    out.append(_txt(d))
                    break
                if d.type == "function_declarator":
                    return []
                d = d.child_by_field_name("declarator")
            return out

        def visit(n: Node, rel: str) -> None:
            for c in n.named_children:
                if c.type == "declaration":
                    if any(k.type == "type_qualifier" and _txt(k) == "const" for k in c.children):
                        continue
                    for d in c.children_by_field_name("declarator"):
                        names.update(decl_names(d))
                elif c.type.startswith("preproc_"):
                    visit(c, rel)

        for u in self.P.units:
            visit(u.root, u.rel)
        return names

    @staticmethod
    def _locals(f: Func) -> set[str]:
        out: set[str] = set()
        for n in _walk(f.node):
            if n.type in ("declaration", "parameter_declaration"):
                for d in n.children_by_field_name("declarator"):
                    while d is not None:
                        if d.type == "identifier":
                            out.add(_txt(d))
                            break
                        d = d.child_by_field_name("declarator")
        return out

    @staticmethod
    def _root_var(n: Node | None) -> str | None:
        while n is not None:
            if n.type == "identifier":
                return _txt(n)
            if n.type == "parenthesized_expression" and n.named_children:
                n = n.named_children[0]
            elif n.type == "subscript_expression":
                n = n.child_by_field_name("argument")
            elif n.type == "field_expression":
                op = n.child_by_field_name("operator")
                if op is not None and _txt(op) == "->":
                    return None
                n = n.child_by_field_name("argument")
            else:
                return None
        return None

    def rt3(self) -> None:
        globs = self._globals()
        if not globs:
            return
        writers: dict[str, dict[str, tuple[str, int]]] = {}  # var -> task -> (rel, line)
        for entry in self.tasks:
            if entry not in self.P.funcs:
                continue
            for fn in self.P.reach(entry):
                for f in self.P.funcs[fn]:
                    loc = self._locals(f)
                    for n in _walk(f.node):
                        t = None
                        if n.type == "assignment_expression":
                            t = n.child_by_field_name("left")
                        elif n.type == "update_expression":
                            t = n.child_by_field_name("argument")
                        v = self._root_var(t) if t is not None else None
                        if v and v in globs and v not in loc:
                            writers.setdefault(v, {}).setdefault(entry, (f.rel, _line(n)))
        for v, by in sorted(writers.items()):
            if len(by) >= 2:
                (t1, (rel, line)), (t2, _) = sorted(by.items())[:2]
                self.add(
                    "RT3_SHARED_WRITER",
                    "warning",
                    rel,
                    line,
                    f"'{v}' is written from two tasks ({t1} and {t2}); give it a single writer "
                    "(double-buffered snapshot, or one volatile 32-bit value) (real-time rule 3)",
                )

    # ---- RT4 -------------------------------------------------------------
    def _is_pacing(self, c: Call) -> bool:
        n = c.name
        if n in self.allowed or n in self.extra_block or n in PACING:
            if n in SEMA_TIMEOUT:
                a = c.args()
                return len(a) > SEMA_TIMEOUT[n] and not self.P.is_zero(a[SEMA_TIMEOUT[n]])
            return True
        if n in PACING_TIMED:
            a = c.args()
            i = TIMED[n]
            return len(a) > i and not self.P.is_zero(a[i])
        return False

    def _blocks(self, node: Node, rel: str, seen: set[str]) -> bool:
        """A pacing call outside any if/switch/loop body/ternary branch, or in an
        unconditionally called function."""
        stack = [node]
        while stack:
            n = stack.pop()
            if n.type in (
                "if_statement",
                "switch_statement",
                "for_statement",
                "while_statement",
                "do_statement",
                "conditional_expression",
            ):
                for key in ("condition", "initializer", "update"):
                    ch = n.child_by_field_name(key)
                    if ch is not None:
                        stack.append(ch)
                continue
            if n.type == "call_expression":
                fn = n.child_by_field_name("function")
                if fn is not None and fn.type == "identifier":
                    c = Call(_txt(fn), n, rel)
                    if self._is_pacing(c):
                        return True
                    if c.name in self.P.funcs and c.name not in seen:
                        seen.add(c.name)
                        for f in self.P.funcs[c.name]:
                            body = f.node.child_by_field_name("body")
                            if body is not None and self._blocks(body, f.rel, seen):
                                return True
            stack.extend(n.children)
        return False

    @staticmethod
    def _infinite(n: Node) -> bool:
        if n.type == "for_statement":
            return n.child_by_field_name("condition") is None
        if n.type == "while_statement":
            c = n.child_by_field_name("condition")
            return c is not None and re.sub(r"[\s()]", "", _txt(c)) in ("1", "true")
        return False

    def rt4(self) -> None:
        for entry in self.tasks:
            for f in self.P.funcs.get(entry, []):
                for n in _walk(f.node):
                    if self._infinite(n):
                        body = n.child_by_field_name("body")
                        if body is not None and not self._blocks(body, f.rel, {entry}):
                            self.add(
                                "RT4_TASK_NO_BLOCK",
                                "error",
                                f.rel,
                                _line(n),
                                f"task loop in {entry}() has no blocking call (I2S write, "
                                "vTaskDelayUntil, notification wait...) on each pass, so it can "
                                "starve the idle task and trip the watchdog; approximate check "
                                "(real-time rule 4)",
                            )

    # ---- RT7 -------------------------------------------------------------
    def _ticks(self, expr: str, hz: int, depth: int = 0) -> int | None:
        """Evaluate a delay expression (numbers, macros, consts, pdMS_TO_TICKS) to ticks."""
        s = re.sub(r"\s+", "", _STRIP_RE.sub(" ", expr))
        if depth > 6:
            return None
        for _ in range(8):  # innermost pdMS_TO_TICKS first
            m = re.search(r"pdMS_TO_TICKS\(([^()]*)\)", s)
            if not m:
                break
            ms = self._ticks(m.group(1), hz, depth + 1)
            if ms is None:
                return None
            s = s[: m.start()] + str(ms * hz // 1000) + s[m.end():]
        s = re.sub(r"\((?:u?int\d*_t|TickType_t|int|unsigned|long)\)", "", s)
        s = re.sub(r"(?<=\d)[uUlL]+\b", "", s)

        def sub(m: re.Match) -> str:
            v = self.P.macros.get(m.group())
            if v is None:
                return m.group()
            r = self._ticks(v, hz, depth + 1)
            return str(r) if r is not None else m.group()

        s = re.sub(r"\b[A-Za-z_]\w*\b", sub, s)
        if not re.fullmatch(r"[\d+\-*/%()]+", s):
            return None
        try:
            v = eval(s.replace("/", "//"), {"__builtins__": {}}, {})
        except (SyntaxError, ValueError, ZeroDivisionError, TypeError):
            return None
        return v if isinstance(v, int) else None

    def rt7(self) -> None:
        hz = int(self.cfg.get("tick_hz") or 1000)
        for spec in (self.cfg.get("tasks") or {}).values():
            if not isinstance(spec, dict) or not spec.get("entry") or not spec.get("period_ms"):
                continue
            entry, period = spec["entry"], spec["period_ms"]
            for f in self.P.funcs.get(entry, []):
                for n in _walk(f.node):
                    body = n.child_by_field_name("body") if self._infinite(n) else None
                    if body is None:
                        continue
                    calls = _calls_in(body, f.rel)
                    untils = [c for c in calls if c.name in ("vTaskDelayUntil", "xTaskDelayUntil")]
                    if not untils:
                        for c in calls:
                            if c.name == "vTaskDelay":
                                self.add(
                                    "RT7_PERIOD_DRIFT", "error", f.rel, c.line,
                                    f"{entry} paces its {period} ms loop with vTaskDelay, so its "
                                    "period drifts by however long the scan took; use "
                                    "vTaskDelayUntil with a TickType_t last-wake time (build "
                                    "procedure phase 4 / CLAUDE.md scan every 1 ms)")
                        continue
                    for c in untils:
                        a = c.args()
                        if len(a) < 2:
                            continue
                        t = self._ticks(_txt(a[1]), hz)
                        if t is None:
                            continue
                        if t == 0:
                            self.add(
                                "RT7_PERIOD_DRIFT", "warning", f.rel, c.line,
                                f"{entry}'s {c.name} period '{_txt(a[1])}' is 0 ticks at "
                                f"{hz} Hz, so it never waits; the tick is too coarse for "
                                f"{period} ms (raise CONFIG_FREERTOS_HZ)")
                        elif t * 1000 != period * hz:
                            self.add(
                                "RT7_PERIOD_MISMATCH", "warning", f.rel, c.line,
                                f"{entry}'s {c.name} period '{_txt(a[1])}' is {t} ticks = "
                                f"{t * 1000 / hz:g} ms at {hz} Hz, but the profile says "
                                f"{period} ms")

    # ---- RT5 -------------------------------------------------------------
    def rt5_double(self) -> None:
        msg_lit = (
            "floating literal '{}' is double precision; write it with an f suffix "
            "(real-time rule 5)"
        )
        for u in self.P.units:
            for n in _walk(u.root):
                t = n.type
                if t == "primitive_type" and _txt(n) == "double":
                    self.add(
                        "RT5_DOUBLE",
                        "error",
                        u.rel,
                        _line(n),
                        "'double' type; use float (real-time rule 5)",
                    )
                elif t == "sized_type_specifier" and "double" in _txt(n).split():
                    self.add(
                        "RT5_DOUBLE",
                        "error",
                        u.rel,
                        _line(n),
                        "'long double' type; use float (real-time rule 5)",
                    )
                elif t == "number_literal":
                    s = _txt(n)
                    if self._is_float_lit(s) and s[-1] not in "fF":
                        self.add("RT5_DOUBLE", "error", u.rel, _line(n), msg_lit.format(s))
                elif t == "call_expression":
                    fn = n.child_by_field_name("function")
                    if fn is not None and fn.type == "identifier" and _txt(fn) in DOUBLE_MATH:
                        nm = _txt(fn)
                        self.add(
                            "RT5_DOUBLE",
                            "error",
                            u.rel,
                            _line(n),
                            f"{nm}() works in double precision; use {nm}f() (real-time rule 5)",
                        )
                elif t == "identifier" and _txt(n) in DOUBLE_CONSTS:
                    self.add(
                        "RT5_DOUBLE",
                        "error",
                        u.rel,
                        _line(n),
                        f"{_txt(n)} is a double constant; write the value with an f suffix "
                        "(real-time rule 5)",
                    )
                elif t in ("preproc_def", "preproc_function_def"):
                    self._macro_double(u.rel, n)

    @staticmethod
    def _is_float_lit(s: str) -> bool:
        if s[:2] in ("0x", "0X"):
            return "p" in s.lower()
        return "." in s or "e" in s.lower()

    def _macro_double(self, rel: str, n: Node) -> None:
        val = n.child_by_field_name("value")
        if val is None:
            return
        raw = _txt(val)
        text = _HEX_RE.sub(
            " ",
            _STRIP_RE.sub(
                lambda m: (
                    " " * len(m.group()) if "\n" not in m.group() else "\n" * m.group().count("\n")
                ),
                raw,
            ),
        )
        base = _line(val)
        for m in _FLOAT_RE.finditer(text):
            if m.group(1) not in ("f", "F"):
                self.add(
                    "RT5_DOUBLE",
                    "error",
                    rel,
                    base + text.count("\n", 0, m.start()),
                    f"floating literal '{m.group()}' in a macro is double precision; write "
                    "it with an f suffix (real-time rule 5)",
                )
        for m in re.finditer(r"\bdouble\b", text):
            self.add(
                "RT5_DOUBLE",
                "error",
                rel,
                base + text.count("\n", 0, m.start()),
                "'double' type in a macro; use float (real-time rule 5)",
            )
        for m in _MACRO_MATH_RE.finditer(text):
            self.add(
                "RT5_DOUBLE",
                "error",
                rel,
                base + text.count("\n", 0, m.start()),
                f"{m.group(1)}() in a macro works in double precision; use "
                f"{m.group(1)}f() (real-time rule 5)",
            )
        for m in re.finditer(r"\bM_[A-Z0-9_]+\b", text):
            if m.group() in DOUBLE_CONSTS:
                self.add(
                    "RT5_DOUBLE",
                    "error",
                    rel,
                    base + text.count("\n", 0, m.start()),
                    f"{m.group()} is a double constant (real-time rule 5)",
                )

    def _isrs(self) -> dict[str, str]:
        """ISR function name -> why."""
        isrs: dict[str, str] = {}
        for name in self.P.funcs:
            if name.endswith("_isr"):
                isrs[name] = "named *_isr"
        for fl in self.P.funcs.values():
            for f in fl:
                for c in f.calls:
                    if c.name in ISR_REG_APIS:
                        for a in c.args():
                            for n in _walk(a):
                                if n.type == "identifier" and _txt(n) in self.P.funcs:
                                    isrs.setdefault(_txt(n), f"registered with {c.name}()")
        if any(c.name in ISR_REG_APIS for fl in self.P.funcs.values() for f in fl for c in f.calls):
            for u in self.P.units:
                for n in _walk(u.root):
                    if n.type == "initializer_pair":
                        d = n.child_by_field_name("designator")
                        v = n.child_by_field_name("value")
                        fld = next(
                            (c for c in (d.children if d else []) if c.type == "field_identifier"),
                            None,
                        )
                        if (
                            fld is not None
                            and v is not None
                            and v.type == "identifier"
                            and CALLBACK_FIELD.match(_txt(fld))
                            and _txt(v) in self.P.funcs
                        ):
                            isrs.setdefault(_txt(v), f"installed as {_txt(fld)} callback")
        return isrs

    def rt5_isr(self) -> None:
        for isr, why in self._isrs().items():
            parent = self.P.reach(isr)
            for fn in parent:
                chain = " → ".join(_chain(parent, fn))
                for f in self.P.funcs[fn]:
                    for n in _walk(f.node):
                        bad = None
                        if n.type == "primitive_type" and _txt(n) in ("float", "double"):
                            bad = f"{_txt(n)} type"
                        elif n.type == "number_literal" and self._is_float_lit(_txt(n)):
                            bad = f"floating literal {_txt(n)}"
                        elif n.type == "call_expression":
                            c = n.child_by_field_name("function")
                            if c is not None and _txt(c) in (DOUBLE_MATH | FLOAT_MATH):
                                bad = f"{_txt(c)}()"
                        if bad:
                            self.add(
                                "RT5_ISR_FLOAT",
                                "error",
                                f.rel,
                                _line(n),
                                f"{bad} inside ISR {isr} ({why}; path {chain}); no "
                                "floating point in ISRs (real-time rule 5)",
                            )

    # ---- RT6 -------------------------------------------------------------
    def rt6(self) -> None:
        startup = self.cfg.get("startup_function") or "app_main"
        if startup not in self.P.funcs:
            return
        events: list[tuple[Call, str]] = []  # call, helper name or ""
        for f in self.P.funcs[startup]:
            for c in f.calls:
                events.append((c, ""))
                if c.name in self.P.funcs and c.name != startup:
                    for h in self.P.funcs[c.name]:
                        events.extend((hc, c.name) for hc in h.calls)
        stages = [s for s in (self.cfg.get("startup_order") or []) if isinstance(s, dict)]
        first: dict[str, int] = {}
        for s in stages:
            pats = s.get("calls") or []
            for i, (c, _) in enumerate(events):
                if any(fnmatch.fnmatchcase(c.name, p) for p in pats):
                    first[s["stage"]] = i
                    break
        present = [s["stage"] for s in stages if s["stage"] in first]
        top = None
        for st in present:
            if top is not None and first[st] < first[top]:
                c, via = events[first[st]]
                c0, via0 = events[first[top]]
                self.add(
                    "RT6_STARTUP_ORDER",
                    "error",
                    c.rel,
                    c.line,
                    f"startup stage '{st}' ({c.name}{self._via(via)}) runs before stage "
                    f"'{top}' ({c0.name}{self._via(via0)}, line {c0.line}); required order: "
                    f"{', '.join(s['stage'] for s in stages)} (real-time rule 6)",
                )
            elif top is None or first[st] > first[top]:
                top = st
        creates = [(c, via) for c, via in events if c.name.startswith("xTaskCreate")]
        rt_idx = [
            i
            for i, (c, _) in enumerate(creates)
            if c.args() and self.tasks.get(_txt(c.args()[0])) is True
        ]
        if rt_idx and rt_idx[-1] != len(creates) - 1:
            c, via = creates[-1]
            ent = _txt(c.args()[0]) if c.args() else "?"
            rc = creates[rt_idx[-1]][0]
            self.add(
                "RT6_STARTUP_ORDER",
                "error",
                c.rel,
                c.line,
                f"task {ent} is created after the audio task ({_txt(rc.args()[0])}, line "
                f"{rc.line}); the audio task must be created last (real-time rule 6)",
            )

    @staticmethod
    def _via(via: str) -> str:
        return f" via {via}()" if via else ""

    def run(self) -> list[Finding]:
        self.rt1()
        self.rt2()
        self.rt3()
        self.rt4()
        self.rt5_double()
        self.rt5_isr()
        self.rt6()
        self.rt7()
        return self.out


def check(project: Path, files: list[Path], cfg: dict[str, Any] | None) -> list[Finding]:
    """Run all real-time rules over `files` (absolute paths under `project`)."""
    return Checker(Path(project), files, cfg or {}).run()
