"""Advisory real-time-rule lint for ESP32 / FreeRTOS C projects (tree-sitter).

`check(project, files, cfg)` returns Findings for these rules. Each message is
"<relpath>:<line>: ..." and ends with the rule number it enforces.

  RT1_AUDIO_BLOCKING (error)   blocking/logging/malloc/mutex/delay call reachable
                               from a realtime task (rule 1)
  RT2_QUEUE_TIMEOUT (error)    queue send/receive/peek timeout not literally 0 (rule 2)
  RT3_SHARED_WRITER (warning)  file-scope variable written from two task entries (rule 3)
  RT4_TASK_NO_BLOCK (error)    task `for(;;)` loop with no blocking call (rule 4)
  RT5_DOUBLE (error)           `double`, unsuffixed float literal, double math call (rule 5)
  RT5_ISR_FLOAT (error)        floating point inside an ISR (rule 5)
  RT6_STARTUP_ORDER (error)    app_main init out of order / audio task not last (rule 6)
  RT7_PERIOD_DRIFT (error)     periodic task (profile period_ms) paces its loop with
                               vTaskDelay instead of vTaskDelayUntil; or (warning) the
                               delay-until period is 0 ticks at the configured tick_hz
  RT7_PERIOD_MISMATCH (warning) delay-until period differs from the profile's period_ms

Config (`realtime:` in the profile), all keys optional::

    realtime:
      tasks: {audio: {entry: audio_task, realtime: true}}   # plus auto-discovery
      allowed_blocking_in_realtime: [i2s_channel_write]
      tick_hz: 1000                   # RT7 (default 1000)
      blocking_calls: [my_wait]       # extra calls that count as blocking for RT4
      startup_function: app_main
      startup_order:
        - {stage: gpio, calls: ["gpio_config", "*_gpio_init"]}
        - {stage: tasks, calls: ["xTaskCreate*"]}

RT7 only checks tasks given `period_ms` (e.g. `scan: {entry: scan_task, period_ms: 1}`).

Tasks are auto-discovered from the first argument of xTaskCreate* calls; only
tasks listed with `realtime: true` get RT1.

Limits (this is an approximation, not a proof):
- The call graph is name-based and follows direct calls only. Calls through
  function pointers, callbacks, or hidden inside macros are not seen.
- Identically named static functions in different files are merged.
- RT4 only checks that some blocking call sits in the loop body (or in a
  function it calls) outside any if/switch/loop body; it cannot prove that the
  call is reached on every iteration.
- RT3 sees assignments, compound assignments and ++/-- to the variable (or its
  fields/elements); writes through pointers or via memcpy/memset are not seen.
- RT6 follows helpers from the startup function one level deep only
  (app_main -> helper -> call); deeper calls are invisible. Stages that never
  appear are skipped.
- RT5 reads #define bodies as text (regex), so it may misjudge exotic macros.
"""

