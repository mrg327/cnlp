"""Deterministic source lint for cnlp projects (tree-sitter based).

`run(project)` scans `*.c` / `*.h` under `main/`, `components/` and `core/`
(skipping `build/`, `managed_components/`, and any file whose first 5 lines
contain "GENERATED by cnlp") and returns Findings sorted by file, line. The
location is the start of the message: "<relpath>:<line>: ...".

Rules: LINT_DIRECT_GPIO, LINT_DRIVER_PIN_FIELD, LINT_INCLUDE, LINT_BANNED_API,
LINT_PURE_CORE (any ESP-IDF/FreeRTOS include under a `core` path component),
LINT_PARSE (warning: tree-sitter ERROR/missing node; the file is still scanned).

Profile: optional `<project>/cnlp-profile.yaml`, merged over
`lint_profile_default.yaml`::

    include_allow: [globs]          # fnmatch globs on the header name; appended
    include_ban: {header: replacement text}   # added/overrides; message names it
    disable: [rule ids]             # rules to turn off, e.g. LINT_DIRECT_GPIO
    sources: [main]                 # scan these dirs instead of main/components/core
    realtime: {...}                 # enables the advisory RT* rules, see cnlp.rtlint

`run(project, profile_path=...)` reads the profile from that file instead of
`<project>/cnlp-profile.yaml`, so a profile can live outside a read-only project.

A header in include_ban is LINT_BANNED_API; otherwise it must match
include_allow or (for "quoted" includes) exist in the project.

Limits: only direct calls are seen. Calls hidden in macro bodies or macro
invocations that expand to gpio calls (and `#define` bodies) are not visible;
the register readback at flash time is the backstop. Function pointers to
gpio_* functions are not flagged.
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass
from importlib import resources
from pathlib import Path

import tree_sitter_c
import yaml
from tree_sitter import Language, Node, Parser

from cnlp.manifest import Finding

GPIO_CALLS = frozenset(
    {
        "gpio_config",
        "gpio_set_direction",
        "gpio_set_pull_mode",
        "gpio_pullup_en",
        "gpio_pullup_dis",
        "gpio_pulldown_en",
        "gpio_pulldown_dis",
        "gpio_reset_pin",
        "gpio_set_intr_type",
        "rtc_gpio_pullup_en",
        "rtc_gpio_pulldown_en",
        "rtc_gpio_init",
        "gpio_iomux_out",
        "esp_rom_gpio_pad_select_gpio",
    }
)
PIN_FIELD_GLOBS = (
    "*_io_num",
    "*_gpio_num",
    "gpio_num",
    "io_num",
    "*_pin",
    "enable_internal_pullup",
)
PIN_FIELDS_EXACT = frozenset({"pull_up_en", "pull_down_en"})
CORE_FORBIDDEN = ("esp_*", "driver/*", "freertos/*", "hal/*", "soc/*", "rom/*", "sdkconfig.h")
SKIP_DIRS = frozenset({"build", "managed_components"})
SCAN_ROOTS = ("main", "components", "core")
MARKER = "GENERATED by cnlp"

_PARSER = Parser(Language(tree_sitter_c.language()))


@dataclass(frozen=True)
class Profile:
    allow: tuple[str, ...]
    ban: dict[str, str]
    disable: frozenset[str] = frozenset()
    sources: tuple[str, ...] = SCAN_ROOTS
    realtime: dict | None = None


def load_profile(project: Path, profile_path: Path | None = None) -> Profile:
    text = resources.files("cnlp").joinpath("lint_profile_default.yaml").read_text("utf-8")
    base = yaml.safe_load(text) or {}
    allow = list(base.get("include_allow", []))
    ban = dict(base.get("include_ban", {}))
    path = Path(profile_path) if profile_path else project / "cnlp-profile.yaml"
    disable: set[str] = set()
    sources: tuple[str, ...] = SCAN_ROOTS
    realtime = None
    if path.is_file():
        over = yaml.safe_load(path.read_text("utf-8")) or {}
        allow += list(over.get("include_allow") or [])
        ban.update(over.get("include_ban") or {})
        disable = set(over.get("disable") or [])
        sources = tuple(over.get("sources") or SCAN_ROOTS)
        realtime = over.get("realtime")
    # An explicit allow for a default-banned header lifts the ban only if the user
    # removes it by mapping it to an empty value.
    ban = {k: v for k, v in ban.items() if v}
    return Profile(tuple(allow), ban, frozenset(disable), sources, realtime)


def _is_generated(text: bytes) -> bool:
    return any(MARKER.encode() in ln for ln in text.splitlines()[:5])


def _source_files(project: Path, roots: tuple[str, ...] = SCAN_ROOTS) -> list[Path]:
    out: list[Path] = []
    for root in roots:
        base = project / root
        if not base.is_dir():
            continue
        for p in base.rglob("*"):
            rel = p.relative_to(project)
            if p.suffix in (".c", ".h") and p.is_file() and not SKIP_DIRS & set(rel.parts):
                out.append(p)
    return sorted(set(out))


def _walk(node: Node):
    stack = [node]
    while stack:
        n = stack.pop()
        yield n
        stack.extend(reversed(n.children))


def _txt(n: Node) -> str:
    return (n.text or b"").decode("utf-8", "replace")


def _pin_field(name: str) -> bool:
    return name in PIN_FIELDS_EXACT or any(fnmatch.fnmatchcase(name, g) for g in PIN_FIELD_GLOBS)


def _project_has_header(project: Path, name: str, here: Path) -> bool:
    if (here.parent / name).is_file():
        return True
    for root in SCAN_ROOTS:
        base = project / root
        if base.is_dir():
            for p in base.rglob(Path(name).name):
                rel = p.relative_to(project)
                if not SKIP_DIRS & set(rel.parts) and p.as_posix().endswith(name):
                    return True
    return False


def _lint_file(project: Path, path: Path, prof: Profile) -> list[tuple[int, Finding]]:
    data = path.read_bytes()
    if _is_generated(data):
        return []
    rel = path.relative_to(project)
    in_core = "core" in rel.parts[:-1]
    tree = _PARSER.parse(data)
    res: list[tuple[int, Finding]] = []

    def add(node: Node, rule: str, sev: str, msg: str) -> None:
        line = node.start_point[0] + 1
        res.append((line, Finding(rule, sev, f"{rel.as_posix()}:{line}: {msg}")))  # type: ignore[arg-type]

    parse_lines: set[int] = set()
    for n in _walk(tree.root_node):
        if n.type == "ERROR" or n.is_missing:
            line = n.start_point[0] + 1
            if line not in parse_lines:
                parse_lines.add(line)
                add(
                    n,
                    "LINT_PARSE",
                    "warning",
                    "could not fully parse this line; lint may be incomplete",
                )
        elif n.type == "call_expression":
            fn = n.child_by_field_name("function")
            if fn is not None and fn.type == "identifier" and _txt(fn) in GPIO_CALLS:
                add(
                    n,
                    "LINT_DIRECT_GPIO",
                    "error",
                    f"direct call to {_txt(fn)}(); use the generated board_pins_init(); "
                    "change the pin in spec.cnl",
                )
        elif n.type == "field_designator":
            ident = next((c for c in n.children if c.type == "field_identifier"), None)
            if ident is not None and _pin_field(_txt(ident)):
                add(n, "LINT_DRIVER_PIN_FIELD", "error", _field_msg(_txt(ident)))
        elif n.type == "assignment_expression":
            left = n.child_by_field_name("left")
            if left is not None and left.type == "field_expression":
                f = left.child_by_field_name("field")
                if f is not None and _pin_field(_txt(f)):
                    add(n, "LINT_DRIVER_PIN_FIELD", "error", _field_msg(_txt(f)))
        elif n.type == "preproc_include":
            p = n.child_by_field_name("path")
            if p is None or p.type not in ("system_lib_string", "string_literal"):
                continue
            quoted = p.type == "string_literal"
            hdr = _txt(p)[1:-1]
            if in_core and any(fnmatch.fnmatchcase(hdr, g) for g in CORE_FORBIDDEN):
                add(
                    n,
                    "LINT_PURE_CORE",
                    "error",
                    f"#include <{hdr}> in the pure core; core code must not use ESP-IDF or "
                    "FreeRTOS headers (move hardware access to the generated layer)",
                )
            if hdr in prof.ban:
                add(n, "LINT_BANNED_API", "error", f"#include {hdr} is banned: {prof.ban[hdr]}")
            elif (
                any(fnmatch.fnmatchcase(hdr, g) for g in prof.allow)
                or (quoted and _project_has_header(project, hdr, path))
                or (in_core and any(fnmatch.fnmatchcase(hdr, g) for g in CORE_FORBIDDEN))
            ):
                pass  # allowed, or already reported as LINT_PURE_CORE
            else:
                add(n, "LINT_INCLUDE", "error", f"#include {hdr} is not on the header allowlist")
    return res


def _field_msg(name: str) -> str:
    return (
        f"driver config field '{name}' set in app code; "
        "pass the generated board_<bus>_config() unchanged"
    )


def run(project: Path, profile_path: Path | None = None) -> list[Finding]:
    """Lint a project directory; findings sorted by file then line."""
    project = Path(project)
    prof = load_profile(project, profile_path)
    files = _source_files(project, prof.sources)
    keyed: list[tuple[str, int, Finding]] = []
    for f in files:
        rel = f.relative_to(project).as_posix()
        for line, fnd in _lint_file(project, f, prof):
            keyed.append((rel, line, fnd))
    if prof.realtime is not None:
        from cnlp import rtlint

        for fnd in rtlint.check(project, files, prof.realtime):
            m = re.match(r"(.*?):(\d+): ", fnd.message)
            keyed.append((m.group(1), int(m.group(2)), fnd) if m else ("", 0, fnd))
    keyed = [t for t in keyed if t[2].rule not in prof.disable]
    keyed.sort(key=lambda t: (t[0], t[1]))
    return [t[2] for t in keyed]
